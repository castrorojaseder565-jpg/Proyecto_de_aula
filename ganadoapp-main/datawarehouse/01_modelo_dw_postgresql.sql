-- BoviControl: almacén analítico para PostgreSQL.
-- Origen operacional: MySQL (ganado, vacuna, leche_registro).
-- Ejecutar una vez en la base PostgreSQL destinada al DW.

CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;

-- STAGING: copia de trabajo de las tablas origen. Apache Hop las carga.
CREATE TABLE IF NOT EXISTS staging.stg_ganado (
    id BIGINT PRIMARY KEY,
    codigo_identificacion VARCHAR(50),
    numero_arete VARCHAR(30),
    marca_hierro VARCHAR(20),
    nombre VARCHAR(100),
    raza VARCHAR(50),
    peso NUMERIC(10,2),
    edad NUMERIC(10,2),
    unidad_tiempo_edad VARCHAR(20),
    sexo VARCHAR(20),
    estado_salud VARCHAR(50),
    propietario VARCHAR(100),
    extraido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staging.stg_vacuna (
    id BIGINT PRIMARY KEY,
    ganado_id BIGINT,
    nombre VARCHAR(100),
    fecha_aplicacion DATE,
    proxima_dosis DATE,
    intervalo_cantidad INTEGER,
    intervalo_meses INTEGER,
    unidad_tiempo VARCHAR(20),
    estado VARCHAR(50),
    extraido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staging.stg_leche_registro (
    id BIGINT PRIMARY KEY,
    ganado_id BIGINT,
    fecha_registro DATE,
    turno VARCHAR(20),
    litros NUMERIC(10,2),
    observacion VARCHAR(255),
    created_at TIMESTAMP,
    extraido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- DIMENSIONES
CREATE TABLE IF NOT EXISTS dw.dim_tiempo (
    sk_fecha INTEGER PRIMARY KEY, -- YYYYMMDD; -1 representa fecha desconocida
    fecha DATE UNIQUE,
    anio SMALLINT,
    trimestre SMALLINT,
    mes SMALLINT,
    nombre_mes VARCHAR(15),
    dia SMALLINT,
    dia_semana SMALLINT,
    nombre_dia VARCHAR(15),
    anio_mes CHAR(7)
);

CREATE TABLE IF NOT EXISTS dw.dim_bovino (
    sk_bovino BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bovino_origen BIGINT UNIQUE,
    codigo_identificacion VARCHAR(50),
    numero_arete VARCHAR(30),
    marca_hierro VARCHAR(20),
    nombre VARCHAR(100),
    raza VARCHAR(50),
    peso NUMERIC(10,2),
    edad NUMERIC(10,2),
    unidad_tiempo_edad VARCHAR(20),
    sexo VARCHAR(20),
    estado_salud VARCHAR(50),
    propietario VARCHAR(100),
    es_desconocido BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS dw.dim_turno (
    sk_turno SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno VARCHAR(20) UNIQUE NOT NULL,
    es_desconocido BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS dw.dim_tipo_vacuna (
    sk_tipo_vacuna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    es_desconocido BOOLEAN NOT NULL DEFAULT FALSE
);

-- HECHOS. Grano leche: una fila por registro de leche (bovino, fecha y turno).
CREATE TABLE IF NOT EXISTS dw.fact_produccion_leche (
    id_registro_origen BIGINT PRIMARY KEY,
    sk_bovino BIGINT NOT NULL REFERENCES dw.dim_bovino(sk_bovino),
    sk_fecha INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    sk_turno SMALLINT NOT NULL REFERENCES dw.dim_turno(sk_turno),
    litros NUMERIC(10,2) NOT NULL,
    observacion VARCHAR(255)
);

-- Grano vacuna: una fila por aplicación registrada en BoviControl.
-- La fecha de próxima dosis usa una segunda relación hacia dim_tiempo.
CREATE TABLE IF NOT EXISTS dw.fact_vacunacion (
    id_vacuna_origen BIGINT PRIMARY KEY,
    sk_bovino BIGINT NOT NULL REFERENCES dw.dim_bovino(sk_bovino),
    sk_tipo_vacuna BIGINT NOT NULL REFERENCES dw.dim_tipo_vacuna(sk_tipo_vacuna),
    sk_fecha_aplicacion INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    sk_fecha_proxima_dosis INTEGER NOT NULL REFERENCES dw.dim_tiempo(sk_fecha),
    intervalo_cantidad INTEGER,
    intervalo_meses INTEGER,
    unidad_tiempo VARCHAR(20),
    estado_origen VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS ix_fact_leche_fecha ON dw.fact_produccion_leche(sk_fecha);
CREATE INDEX IF NOT EXISTS ix_fact_leche_bovino ON dw.fact_produccion_leche(sk_bovino);
CREATE INDEX IF NOT EXISTS ix_fact_vacunacion_fecha ON dw.fact_vacunacion(sk_fecha_aplicacion);
CREATE INDEX IF NOT EXISTS ix_fact_vacunacion_proxima ON dw.fact_vacunacion(sk_fecha_proxima_dosis);
CREATE INDEX IF NOT EXISTS ix_fact_vacunacion_bovino ON dw.fact_vacunacion(sk_bovino);

