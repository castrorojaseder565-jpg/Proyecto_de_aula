-- Calendario de ejemplo: amplía el intervalo según las fechas de tu origen.
INSERT INTO dw.dim_tiempo
    (sk_fecha, fecha, anio, trimestre, mes, nombre_mes, dia, dia_semana, nombre_dia, anio_mes)
SELECT
    TO_CHAR(f, 'YYYYMMDD')::INTEGER,
    f::DATE,
    EXTRACT(YEAR FROM f)::SMALLINT,
    EXTRACT(QUARTER FROM f)::SMALLINT,
    EXTRACT(MONTH FROM f)::SMALLINT,
    TO_CHAR(f, 'TMMonth'),
    EXTRACT(DAY FROM f)::SMALLINT,
    EXTRACT(ISODOW FROM f)::SMALLINT,
    TO_CHAR(f, 'TMDay'),
    TO_CHAR(f, 'YYYY-MM')
FROM GENERATE_SERIES(DATE '2020-01-01', DATE '2035-12-31', INTERVAL '1 day') AS s(f)
ON CONFLICT (sk_fecha) DO NOTHING;

